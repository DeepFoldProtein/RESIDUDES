#!/usr/bin/env python3
"""Regenerate data/manifest.toml from the team's reference copies (maintainers only).

Every data file residudes-qa needs is listed with its size, sha256, licence note and where it can
be fetched from: `local` = the reference copy on the DeepFold cluster (GPFS), `url` = a public
upstream that serves the identical bytes. `residudes-qa data fetch` copies or links from these and
refuses a file whose sha256 differs.

    python3 scripts/dev/make_manifest.py > data/manifest.toml
"""
import hashlib
import sys
from pathlib import Path

A = Path("/gpfs/deepfold/casp/casp17/analysis")
XGB = A / "XGBDimerScorer_tool" / "models"
EMA = A / "EMA" / "data"
MPNN = A / "MassiveClustering_tool" / "proteinmpnn" / "run" / "model_weights"
MPNN_URL = "https://github.com/dauparas/ProteinMPNN/raw/main"
MPNN_SUBDIR = {"v": "vanilla_model_weights", "s": "soluble_model_weights", "ca": "ca_model_weights"}

# (relative path in the data root, local reference copy, licence, upstream url or None)
entries = []
for f in sorted(XGB.glob("*.json")):
    entries.append((f"xgb_models/{f.name}", f, "DeepFold (team-trained XGBoost)", None))
entries += [
    ("ema/dfire/dfire_v2_energy_table_with_types.pt", EMA / "dfire" / "dfire_v2_energy_table_with_types.pt",
     "DeepFold re-implementation of DFIRE2 (Yang & Zhou)", None),
    ("ema/dunbrack/ALL.bbdep.rotamers.lib", EMA / "dunbrack" / "ALL.bbdep.rotamers.lib",
     "Dunbrack bbdep2010 - academic licence, do not redistribute publicly", None),
    ("ema/dunbrack/NDRD_TCBIG.txt.gz", EMA / "dunbrack" / "NDRD_TCBIG.txt.gz",
     "Dunbrack NDRD - academic licence, do not redistribute publicly", None),
    ("ema/dunbrack/ndrd_tcbig_table.pkl", EMA / "dunbrack" / "ndrd_tcbig_table.pkl",
     "cache derived from NDRD_TCBIG (same licence)", None),
    ("ema/potentials/aadars_v3_full.pt", EMA / "potentials" / "aadars_v3_full.pt",
     "DeepFold (team-trained aADARS v3)", None),
]
for f in sorted(MPNN.glob("*.pt")):
    url = None
    stem = f.stem                                  # v_48_020, s_48_020, ca_48_020, bidir_table
    kind = stem.split("_")[0]
    if kind in MPNN_SUBDIR:
        url = f"{MPNN_URL}/{MPNN_SUBDIR[kind]}/v_{stem.split('_', 1)[1]}.pt"
    entries.append((f"proteinmpnn/model_weights/{f.name}", f, "ProteinMPNN (MIT, Dauparas et al. 2022)", url))


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


out = sys.stdout
out.write("# residudes-qa data manifest - generated by scripts/dev/make_manifest.py; do not edit by hand.\n")
out.write("# path = location under the data root ($RESIDUDES_QA_DATA or residudes-qa/data/files)\n\n")
for rel, src, lic, url in entries:
    if not src.exists():
        sys.exit(f"missing reference copy: {src}")
    out.write("[[file]]\n")
    out.write(f'path = "{rel}"\n')
    out.write(f"size = {src.stat().st_size}\n")
    out.write(f'sha256 = "{sha256(src)}"\n')
    out.write(f'license = "{lic}"\n')
    out.write(f'local = "{src}"\n')
    if url:
        out.write(f'url = "{url}"\n')
    out.write("\n")
