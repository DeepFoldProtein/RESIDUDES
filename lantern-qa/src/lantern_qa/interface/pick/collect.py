"""Final-pick folder assembly.

Generalized from H1335 ``47_final_5.py``.  Given a ``picks_df`` (output of
:func:`lantern_qa.interface.pick.per_cluster.pick_per_cluster` or a curated subset
thereof), copies the source CIFs + summary.json into
``<output>/final_picks/``, writes a ``MANIFEST.csv`` with the full feature
table and a ``README.md`` with selection rationale.
"""
from __future__ import annotations

import shutil
from pathlib import Path
from typing import Optional

import pandas as pd


def _rationale_line(row: pd.Series) -> str:
    """Build a one-liner rationale from the available feature columns."""
    parts: list[str] = []
    if pd.notna(row.get("xgb_pred")):
        parts.append(f"xgb={float(row['xgb_pred']):.3f}")
    if pd.notna(row.get("json_iptm")):
        parts.append(f"iptm={float(row['json_iptm']):.3f}")
    if pd.notna(row.get("json_ranking_score")):
        parts.append(f"rank={float(row['json_ranking_score']):.3f}")
    if pd.notna(row.get("n_inter_clash_17")):
        parts.append(f"clash_inter={int(row['n_inter_clash_17'])}")
    if pd.notna(row.get("mpnn_iface_n_residues")):
        parts.append(f"mpnn_iface={int(row['mpnn_iface_n_residues'])}")
    if row.get("kind"):
        parts.append(str(row["kind"]))
    return "  ".join(parts)


def collect_final_picks(
    picks_df: pd.DataFrame,
    output_dir: str | Path,
    max_picks: int = 5,
    sort_by: Optional[list[str]] = ("kind", "xgb_pred"),
) -> Path:
    """Copy CIFs + summary.json into ``<output_dir>/final_picks/``.

    Parameters
    ----------
    picks_df
        DataFrame of picks (one row per pick).  Must contain ``src_cif``,
        ``tag``, ``kind``, ``cluster_id`` plus the metric columns used for
        the rationale (xgb_pred / json_iptm / ...).  Order in the returned
        folder matches the row order in ``picks_df`` after the optional
        ``sort_by`` reorder.
    output_dir
        Destination root.  Subdir ``final_picks/`` is created and overwritten.
    max_picks
        Hard cap on number of CIFs copied (default 5 = CASP submission limit).
    sort_by
        Optional ``df.sort_values`` argument used **before** truncation.
        Pass ``None`` to preserve incoming order.
    """
    output_dir = Path(output_dir)
    out = output_dir / "final_picks"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    df = picks_df.copy()
    if sort_by is not None:
        cols = [c for c in sort_by if c in df.columns]
        if cols:
            df = df.sort_values(by=cols, ascending=[c != "xgb_pred" for c in cols])
    if max_picks is not None and len(df) > max_picks:
        df = df.head(max_picks).reset_index(drop=True)

    manifest_rows: list[dict] = []
    for i, row in df.iterrows():
        num = i + 1
        tag = str(row.get("tag", f"pick{num}"))
        cif_src = Path(str(row["src_cif"]))
        cif_dst = out / f"model_{num}_{tag}.cif"
        try:
            shutil.copy(cif_src, cif_dst)
        except Exception as exc:  # noqa: BLE001
            print(f"  WARN: failed to copy {cif_src} → {cif_dst}: {exc}", flush=True)
            continue
        # summary.json (CIF sibling) if present
        sj = cif_src.parent / "summary.json"
        if sj.exists():
            shutil.copy(sj, out / f"model_{num}_{tag}_summary.json")

        rec = {"model_num": int(num), "tag": tag}
        rec.update({k: v for k, v in row.to_dict().items() if k not in rec})
        rec["dst_cif"] = str(cif_dst)
        manifest_rows.append(rec)

    manifest = pd.DataFrame(manifest_rows)
    manifest.to_csv(out / "MANIFEST.csv", index=False)
    print(
        f"  collect_final_picks: copied {len(manifest)} / {len(df)} models → {out}",
        flush=True,
    )

    # README with per-pick rationale
    lines: list[str] = [
        "# Final picks",
        "",
        f"Generated by lantern-qa interface.  Source pool: {len(picks_df)} pick candidates",
        f"(capped at {max_picks}).",
        "",
        "## Summary",
        "",
        "| # | tag | cluster | kind | rationale |",
        "|---|---|---|---|---|",
    ]
    for _, r in manifest.iterrows():
        lines.append(
            f"| {int(r['model_num'])} | `{r.get('tag','')}` | "
            f"{int(r.get('cluster_id', -1))} | {r.get('kind','')} | "
            f"{_rationale_line(r)} |"
        )
    lines.extend(["", "## Per-pick details", ""])
    for _, r in manifest.iterrows():
        lines.append(f"### Model {int(r['model_num'])} — `{r.get('tag','')}`")
        lines.append("")
        details = [
            ("kind", r.get("kind")),
            ("cluster_id", r.get("cluster_id")),
            ("variant", r.get("variant")),
            ("method", r.get("method")),
            ("seed", r.get("seed")),
            ("sample", r.get("sample")),
            ("xgb_pred", r.get("xgb_pred")),
            ("json_iptm", r.get("json_iptm")),
            ("json_ranking_score", r.get("json_ranking_score")),
            ("n_inter_clash_17", r.get("n_inter_clash_17")),
            ("mpnn_iface_n_residues", r.get("mpnn_iface_n_residues")),
            ("aadars_frac_cdr_h3", r.get("aadars_frac_cdr_h3")),
            ("aadars_frac_framework", r.get("aadars_frac_framework")),
            ("dfire_v2_per_atom", r.get("dfire_v2_per_atom")),
            ("src_cif", r.get("src_cif")),
        ]
        for k, v in details:
            if v is None or (isinstance(v, float) and pd.isna(v)):
                continue
            lines.append(f"- **{k}**: {v}")
        lines.append("")

    (out / "README.md").write_text("\n".join(lines))
    print(f"  saved: {out/'README.md'} + MANIFEST.csv", flush=True)
    return out
